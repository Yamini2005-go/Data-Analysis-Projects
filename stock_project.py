#performing arima(0,1,0) - since the random shocks are completely new for everyday, it does'nt exhibit correlation and so the same for moving avg
clean_return = df['Daily_Return'].dropna()
adf_result = adfuller(clean_return)

print(f"ADF Statistic")
print(f"ADF Statistic: {adf_result[0]}")
print(f"p-value: {adf_result[1]:.4f}")
print(f"Critical values: ")
for key, value in adf_result[4].items():
  print(f"{key} : {value:.4f}")

if adf_result[1] <= 0.05:
  print("The data is stationary, proceed with 1st order differencing")
else:
  print("The data is non-stationary, differentiate again for further analysis")
#model
