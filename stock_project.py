import pandas as pd
import numpy as np
import math as m

dates = pd.date_range(start='2025-01-01',periods=365)
np.random.seed(42)
initial_price = 100
volatility = 0.015
drift = 0.0006
price_history = [initial_price]

for date in range(1,len(dates)):
  random_shock = np.random.normal(loc=0,scale=volatility)
  tot_daily_change = drift + random_shock
  pre_data = price_history[-1]
  today_price = price_history[-1] * (1 + tot_daily_change)
  price_history.append(today_price)
df = pd.DataFrame(
    {
        'Date' : dates,
        'Closed_price' : price_history
    }
)
df['Daily_Return'] = df['Closed_price'].pct_change()
df['Ma_20'] = df['Closed_price'].rolling(window=20).mean()
df['daily_volatility'] = df['Daily_Return'].rolling(window=14).std()
print(df.tail())
df.to_excel("Stock_data.xlsx",index=False)
print("Data generated and exported!")

